function normalisasiTeks(teks) {
  return teks
    .toLowerCase()
    .replace(/\bkemana\b/g, "ke mana")
    .replace(/\bdimana\b/g, "di mana")
    .replace(/\bgak\b|\bnggak\b|\bga\b/g, "tidak");
}

function renderKartuFrasa(frasa) {
  const elLabel = document.getElementById("potd-label");
  const elPhrase = document.getElementById("potd-phrase");
  const elPronunciation = document.getElementById("potd-pronunciation");
  const elMeaning = document.getElementById("potd-meaning");

  if (!elPhrase) return;

  const lang = localStorage.getItem("gaulingo_lang") || "en";

  if (elLabel) {
    elLabel.textContent = frasa.daerah
      ? `BAHASA ${frasa.daerah.toUpperCase()}`
      : translations[lang]?.potd_label || "PHRASE OF THE DAY";
  }

  elPhrase.textContent = frasa.asli;
  if (elPronunciation) elPronunciation.textContent = frasa.baca;
  if (elMeaning) {
    elMeaning.textContent = `"${lang === "id" ? frasa.arti_id : frasa.arti_en}"`;
  }
}

