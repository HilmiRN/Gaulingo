function cariDanTampilkanFrasa() {
  const q = normalisasiTeks(kalimatDicari.trim());
  const lang = localStorage.getItem("gaulingo_lang") || "en";

  if (!q) {
    if (!daerahTerpilih) {
      renderKartuFrasa(frasaDefault);
      return;
    }
    const defaultDaerah = dataFrasaLokal.find(
      (item) =>
        item.daerah.toLowerCase() === daerahTerpilih.toLowerCase() &&
        item.topik === "terima kasih",
    );
    renderKartuFrasa(defaultDaerah || frasaDefault);
    return;
  }

  const cocok = dataFrasaLokal.find((item) => {
    const sesuaiDaerah =
      !daerahTerpilih ||
      item.daerah.toLowerCase() === daerahTerpilih.toLowerCase();

    const sesuaiKalimat =
      normalisasiTeks(item.topik).includes(q) ||
      normalisasiTeks(item.arti_id).includes(q) ||
      item.arti_en.toLowerCase().includes(q) ||
      item.asli.toLowerCase().includes(q);

    return sesuaiDaerah && sesuaiKalimat;
  });

  if (cocok) {
    if (!daerahTerpilih) {
      daerahTerpilih = cocok.daerah;
      perbaruiTombolDaerah();
    }
    renderKartuFrasa(cocok);
  } else {
    renderKartuFrasa({
      daerah: daerahTerpilih || "",
      asli: lang === "id" ? "Belum ketemu" : "Not found yet",
      baca:
        lang === "id"
          ? "Coba ketik: apa kabar, berapa harganya, numpang lewat"
          : "Try typing: how are you, how much, excuse me",
      arti_id: `Kalimat "${kalimatDicari}" belum ada di daftar`,
      arti_en: `Sentence "${kalimatDicari}" is not in the list yet`,
    });
  }
}

function initKartuBahasaLokal() {
  const tombolDaerah = document.querySelectorAll(".btn-daerah");
  const inputCari = document.getElementById("input-cari-frasa");

  tombolDaerah.forEach((btn) => {
    btn.addEventListener("click", () => {
      const daerah = btn.dataset.daerah;
      daerahTerpilih = daerahTerpilih === daerah ? null : daerah;
      perbaruiTombolDaerah();
      cariDanTampilkanFrasa();
    });
  });

  if (inputCari) {
    inputCari.addEventListener("input", (e) => {
      kalimatDicari = e.target.value;
      cariDanTampilkanFrasa();
    });
  }

  renderKartuFrasa(frasaDefault);
}

